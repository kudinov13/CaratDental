import { DatabaseSync } from 'node:sqlite'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const db = new DatabaseSync(join(__dirname, 'karat.db'))

// Грамматические правки названий услуг: [old, new]
// Выполняются через REPLACE — id и sqns_service_id сохраняются.
const renames = [
  ['первого/второго примоляра', 'первого/второго премоляра'],
  ['ранее удаленного', 'ранее удалённого'],
  ['Диоксид циркониевая', 'Диоксид-циркониевая'],
  ['Комплексная гигиена Зубов', 'Комплексная гигиена зубов'],
  ['молочных Зубов', 'молочных зубов'],
  ['брекет системой', 'брекет-системой'],
  ['брекет-системой со смешанным', 'брекет-системой со смешанным'],
  ['брекет - системы', 'брекет-системы'],
  ['смешенного', 'смешанного'],
  ['Съемный', 'Съёмный'],
  ['съемного', 'съёмного'],
  ['Несъемный', 'Несъёмный'],
  ['твердого', 'твёрдого'],
  ['налетом', 'налётом'],
  ['налета', 'налёта'],
  ['Экспресс гигиена', 'Экспресс-гигиена'],
  ['Активация одна челюсть', 'Активация одной челюсти'],
  ['Активация две челюсти', 'Активация двух челюстей'],
  ['Смена дуги на одну челюсть:', 'Смена дуги на одной челюсти'],
  ['КПО - (анализ', 'КПО — (анализ'],
  ['Фиксация брекет - системы', 'Фиксация брекет-системы'],
  ['Установка ретейнера (одна челюсть)', 'Установка ретейнера (одна челюсть)'],
]

const upd = db.prepare('UPDATE services SET name = REPLACE(name, ?, ?)')
let changed = 0
for (const [from, to] of renames) {
  const r = upd.run(from, to)
  changed += r.changes
}
console.log(`Грамматическая миграция выполнена. Изменено полей: ${changed}`)
